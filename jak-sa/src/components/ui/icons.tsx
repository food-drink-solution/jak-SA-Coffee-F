import type { SVGProps } from "react";

/**
 * Brand/social icons.
 *
 * lucide-react (the app's icon library) intentionally ships no brand icons,
 * so these are provided locally with the exact same contract as lucide icons:
 * they accept an SVGProps<SVGSVGElement> and merge the incoming className,
 * e.g. `<FacebookIcon className="h-5 w-5" aria-hidden />`.
 */

function mergeClassName(className?: string, fallback = "h-5 w-5"): string {
  return className && className.trim().length > 0 ? className : fallback;
}

export function FacebookIcon({ className, ...props }: SVGProps<SVGSVGElement>) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      className={mergeClassName(className)}
      aria-hidden
      {...props}
    >
      <path d="M18 2h-3a5 5 0 0 0-5 5v3H7v4h3v8h4v-8h3l1-4h-4V7a1 1 0 0 1 1-1h3z" />
    </svg>
  );
}

